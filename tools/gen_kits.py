def q(v):
    return '"%s"' % v if isinstance(v, str) else str(v)


def arr(a):
    return '[' + ', '.join(q(x) for x in a) + ']'


def box(mask, x0, z0, x1, z1):
    return dict(kind='stamp', shape='box', mask=mask, **{'from': [x0, 0, z0], 'to': [x1, 'h', z1]})


def disc(mask, cx, cz, r):
    return dict(kind='stamp', shape='disc', mask=mask, center=[cx, cz], radius=r)


def op(kind, **kw):
    d = dict(kind=kind)
    d.update(kw)
    return d


def repeat(along, frm, to, step, ops):
    return dict(kind='repeat', along=along, **{'from': frm}, to=to, step=step, ops=ops)


def inline(o):
    parts = []
    for k, v in o.items():
        parts.append('%s = %s' % (k, arr(v) if isinstance(v, list) else q(v)))
    return '{ ' + ', '.join(parts) + ' }'


def render(pid, theme, district, fmin, fmax, tags, note, ops, special='', function=''):
    L = ['# kits/rooms/%s.toml (apx-gen F3, generated by tools/gen_kits.py): %s' % (pid, note), '[meta]',
         'id = "%s"' % pid, 'level = "MICRO"', 'theme = "%s"' % theme]
    if district:
        L.append('district = "%s"' % district)
    if special:
        L.append('special = "%s"' % special)
    if function:
        L.append('function = "%s"' % function)
    L.append('fits = { min = [%d, 4, %d], max = [%d, 6, %d] }' % (fmin, fmin, fmax, fmax))
    L.append('tags = %s' % arr(tags))
    for o in ops:
        L.append('')
        L.append('[[op]]')
        for k, v in o.items():
            if k == 'ops':
                L.append('ops = [')
                for io in v:
                    L.append('  %s,' % inline(io))
                L.append(']')
            elif isinstance(v, list):
                L.append('%s = %s' % (k, arr(v)))
            else:
                L.append('%s = %s' % (k, q(v)))
    return '\n'.join(L) + '\n'


def cave_base(seed, thr):
    return [box('inner', 2, 2, 'w-2', 'd-2'), disc('core', 'w/2', 'd/2', 'w/4'),
            op('noise', mask='void', seed=seed, scale_cells=3, threshold_1024=thr),
            op('union', dst='void', src='core'), op('intersect', dst='void', src='inner'),
            op('close', mask='void', k=1), op('open', mask='void', k=1),
            op('components', mask='void', keep='largest')]


