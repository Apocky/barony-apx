# tools/gen_kits.py -- writes the F3 structure programs (kits/rooms/*.toml) and kits/districts.toml.
# The TOML files are the source of truth the generator reads; this script only spares typing the
# repeated op syntax. Re-run after editing a definition here:  python tools/gen_kits.py
import os

