def q(v):
    return '"%s"' % v if isinstance(v, str) else str(v)


def arr(a):
    return '[' + ', '.join(arr(x) if isinstance(x, (list, tuple)) else q(x) for x in a) + ']'


def part(op, **kw):
    d = {'op': op}
    d.update({k.rstrip('_'): v for k, v in kw.items()})
    return d


def inline(o):
    return '{ ' + ', '.join('%s = %s' % (k, arr(v) if isinstance(v, list) else q(v)) for k, v in o.items()) + ' }'


def fixture(fid, note, footprint, support, blocks, content, variants, dims, parts):
    L = ['# kits/props/%s.toml (apx-gen F3 prop grammar, generated by tools/gen_dress_kits.py): %s' % (fid, note),
         '[meta]', 'id = "%s"' % fid, 'footprint = %s' % arr(footprint), 'support = "%s"' % support,
         'blocks = %s' % ('true' if blocks else 'false'), 'content = "%s"' % content, 'variants = %d' % variants,
         'dims = %s' % arr(dims), 'palette = %s' % arr([list(c) for c in PAL])]
    for p in parts:
        L += ['', '[[part]]']
        for k, v in p.items():
            if k == 'parts':
                L.append('parts = [')
                L += ['  %s,' % inline(x) for x in v]
                L.append(']')
            else:
                L.append('%s = %s' % (k, arr(v) if isinstance(v, list) else q(v)))
    with open(os.path.join(PROPS, fid + '.toml'), 'w', newline='\n') as f:
        f.write('\n'.join(L) + '\n')


