# ------------------------------------------------------------------ function programs
def fn(fid, note, activities, items, walls, vignettes, clutter, never):
    L = ['# kits/functions/%s.toml (apx-gen F3 function program, generated by tools/gen_dress_kits.py): %s' % (fid, note),
         '[meta]', 'id = "%s"' % fid, 'clutter = %s' % arr(clutter), 'never = %s' % arr(never)]
    for a in activities:
        L += ['', '[[activity]]']
        L += ['%s = %s' % (k, arr(v) if isinstance(v, list) else ('true' if v is True else q(v))) for k, v in a.items()]
    for it in items:
        L += ['', '[[item]]'] + ['%s = %s' % (k, q(v)) for k, v in it.items()]
    # wall trim: the program's own kinds first, then neutral kinds so the Clone Army cap (3 per
    # zone per variant) leaves room; shares scaled to 0.85 (gameplay/20: at least 60 percent of faces)
    walls = list(walls)
    for extra in ['cobweb', 'chains', 'moss', 'graffiti', 'sconce', 'plaque', 'roots']:
        if extra not in [w for w, _ in walls] and extra not in never and len(walls) < 8:
            walls.append((extra, 0.05))
    tot = sum(s for _, s in walls)
    walls = [(w, round(s * 0.85 / tot, 3)) for w, s in walls]
    for wid, share in walls:
        L += ['', '[[wall]]', 'id = "%s"' % wid, 'share = %s' % share]
    for v in vignettes:
        L += ['', '[[vignette]]'] + ['%s = %s' % (k, arr(x) if isinstance(x, list) else q(x)) for k, x in v.items()]
    with open(os.path.join(FUNCS, fid + '.toml'), 'w', newline='\n') as f:
        f.write('\n'.join(L) + '\n')


def act(i, zone, bucket, anchor, around=(), on=(), focal=False):
    d = dict(id=i, zone=zone, bucket=bucket, anchor=anchor)
    if focal:
        d['focal'] = True
    if around:
        d['around'] = list(around)
    if on:
        d['on'] = list(on)
    return d


def item(i, zone, bucket, lo=1, hi=1):
    return dict(id=i, zone=zone, bucket=bucket, min=lo, max=hi)


def vig(i, zone, bucket, parts):
    return dict(id=i, zone=zone, bucket=bucket, parts=parts)


