"""combat_c3_gate.py -- the D93 C3 gate: creature melee on the core, telegraphed, played with REAL input through the QA driver.

    python tools/apx/combat_c3_gate.py --exe build/vs2022/Release/barony.exe [--foe goblin] [--old]
    python tools/apx/hostility_gate.py --exe ... (the calm-start half: seeds 4242 and 777 standing still 60 s)

A goblin (9999 HP, hunting the player) attacks a player with 9999 HP, shield up, after the 10 s calm start. Real keys: Q block, Space dodge.
  telegraph     every creature strike follows a telegraph row (windup animation + whoosh) by >= 300 ms
  hurt          with no defence the strikes cost HP (the creature really fights)
  block         Q held: strikes are blocked (stamina off), not free
  dodge         Space every 600 ms: some strikes land in the 160 ms window and do nothing
  timed block   Q tapped every 600 ms: some strikes land inside the 200 ms window: free, the attacker staggered
The control (--old, APX_COMBAT_OLD=1) must show no creature_strike rows: the old code strikes inside Entity::attack.
"""
import argparse
import datetime
import json
import os
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import apx_locks  # noqa: E402
import combat_qa as cq  # noqa: E402

OUT = Path(r"C:\Apocrypha\diagnostics\combat\c3")


def script(foe):
    L = ["# generated by tools/apx/combat_c3_gate.py", "waitlevel 1 120000", "wait 14000",   # control + 10 s calm (D94)
         "console /apxcombat_arena shield", "wait 800", "console /apxcombat_hp 9999", f"console /apxcombat_foe {foe}", "wait 5000"]
    L += ["# no defence"] + ["console /apxcombat_pull", "wait 1000"] * 4
    L += ["kdown q"] + ["wait 1700", "console /apxcombat_pull"] * 4 + ["kup q", "wait 500"]   # block held
    for i in range(16):                                                                  # dodge every 600 ms
        L += ["key space 60", "wait 540"] + (["console /apxcombat_pull"] if i % 3 == 2 else [])
    for w in (330, 410, 270, 450, 370, 290, 430, 350, 250, 470, 310, 390) * 2:           # timed-block taps at drifting phases
        L += ["key q 100", f"wait {w}"]
    L += ["console /apxcombat_pull"]
    L += ["wait 500", "quit"]
    return "\n".join(L) + "\n"


def ev(rows, n):
    return [r for r in rows if r.get("ev") == n]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--exe", required=True)
    ap.add_argument("--foe", default="goblin")
    ap.add_argument("--old", action="store_true")
    ap.add_argument("--timeout", type=float, default=300)
    a = ap.parse_args()
    run = OUT / "runs" / f"{datetime.datetime.now():%Y%m%d-%H%M%S}-c3-{a.foe}{'-old' if a.old else ''}"
    qa = run / "qa"
    qa.mkdir(parents=True)
    (qa / "cmd.txt").write_text(script(a.foe))
    jsonl = run / "combat.jsonl"
    env = dict(os.environ, BARONY_DATADIR=cq.DATADIR, APX_COMBAT_JSONL=str(jsonl), APX_DIAG_DIR=str(run))
    if a.old:
        env["APX_COMBAT_OLD"] = "1"
    args = [str(Path(a.exe).resolve()), "-windowed", "-size=1280x720", "-quickstart=barbarian", "-apxfloor=1", "-apxmapseed=1234567", f"-apxqa={qa}"]
    slot = apx_locks.take_slot("combat-c3", 4 * 3600)
    try:
        p = subprocess.Popen(args, cwd=run, env=env)
        try:
            p.wait(a.timeout)
            ended = "exited"
        except subprocess.TimeoutExpired:
            p.terminate()
            ended = "timeout-terminated"
    finally:
        slot.unlink(missing_ok=True)
    rows = cq.parse_rows(jsonl)
    st = [r for r in ev(rows, "creature_strike") if r["target_is_player"]]
    tele = ev(rows, "telegraph")
    v = {
        "telegraph": dict(telegraphs=len(tele), strikes=len(st), min_ms=min((r["telegraph_ms"] for r in st), default=None),
                          ok=len(tele) >= 5 and len(st) >= 5 and min((r["telegraph_ms"] for r in st), default=0) >= 300),
        "hurt": dict(strikes_with_damage=sum(1 for r in st if r["dmg"] > 0), ok=any(r["dmg"] > 0 for r in st)),
        "block": dict(n=len(ev(rows, "block")), ok=len(ev(rows, "block")) >= 1),
        "dodge": dict(n=len(ev(rows, "dodged")), dodges=len(ev(rows, "dodge")), ok=len(ev(rows, "dodged")) >= 1),
        "timed_block": dict(n=len(ev(rows, "timed_block")), since_ms=[r["since_press_ms"] for r in ev(rows, "timed_block")][:6], ok=len(ev(rows, "timed_block")) >= 1),
    }
    if a.old:
        ok = len(ev(rows, "creature_strike")) == 0
        v = {"control_no_core_strikes": dict(strikes=len(ev(rows, "creature_strike")), ok=ok)}
    ok = all(x["ok"] for x in v.values())
    (run / "summary.json").write_text(json.dumps(dict(run=str(run), ended=ended, old=a.old, verdicts=v, pass_=ok), indent=1))
    for k, x in v.items():
        print(f"  {k:12s} {'ok  ' if x['ok'] else 'FAIL'} {json.dumps({i: j for i, j in x.items() if i != 'ok'})}")
    print(f"C3 GATE{' (old control)' if a.old else ''}: {'PASS' if ok else 'FAIL'}  {run / 'summary.json'}")
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
