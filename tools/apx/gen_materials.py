"""F4b (D66): translate Barony's per-class damage table into materials.

Reads damagetables[NUMMONSTERS][7] from src/monster.hpp (columns: sword, mace, axe, polearm,
ranged, magic, unarmed), and for each monster picks the material whose kind profile
(impact, shear, pierce) is closest in SHAPE to the seed row, plus a LEVEL that keeps the row's
overall toughness. Writes src/apx/combat/impact_materials.inc. The material parameters live
here only; impact.cpp holds the formula, and this script mirrors it to score profiles.

Run: python tools/apx/gen_materials.py   (from the repo root)
"""
import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "src" / "monster.hpp"
OUT = ROOT / "src" / "apx" / "combat" / "impact_materials.inc"

KINDS = ("IMPACT", "SHEAR", "PIERCE")
# Barony class -> (kind, momentum kg m/s, contact area cm^2). Column order of damagetables.
CLASSES = [("SWORD", 1, 18.0, 0.6), ("MACE", 0, 24.0, 8.0), ("AXE", 1, 22.0, 0.8),
           ("POLEARM", 2, 20.0, 0.25), ("RANGED", 2, 2.4, 0.04), ("MAGIC", None, 0, 0),
           ("UNARMED", 0, 8.0, 10.0)]
SHATTER = 1.5  # hp factor once stress passes fracture (bone shatters, stone cracks)
BIG = 1e9

# name: [(Y, F, k) for IMPACT, SHEAR, PIERCE]
MATERIALS = {
    "FLESH":    [(0.1, BIG, 1.0), (2.0, BIG, 1.0), (5.0, BIG, 1.0)],
    "BONE":     [(0.1, 2.0, 1.2), (8.0, BIG, 1.0), (30.0, BIG, 1.0)],
    "GEL":      [(0.1, BIG, 0.4), (1.0, BIG, 1.4), (5.0, BIG, 0.8)],
    "STONE":    [(0.3, 2.5, 1.0), (20.0, BIG, 1.0), (50.0, BIG, 1.0)],
    "CHITIN":   [(0.3, BIG, 0.9), (15.0, BIG, 1.0), (8.0, BIG, 1.2)],
    "METAL":    [(0.5, BIG, 0.9), (18.0, BIG, 1.0), (35.0, BIG, 1.0)],
    "ETHEREAL": [(0.1, BIG, 0.6), (2.0, BIG, 0.6), (5.0, BIG, 0.5)],
    "PLANT":    [(0.2, BIG, 0.7), (1.0, BIG, 1.4), (10.0, BIG, 0.7)],
    "HIDE":     [(0.1, BIG, 1.0), (6.0, BIG, 0.9), (3.0, BIG, 1.1)],
    "UNIFORM":  [(0.1, BIG, 1.0), (2.0, BIG, 1.0), (5.0, BIG, 1.0)],  # control: same as flesh
}
NAMES = list(MATERIALS)

# Spec 04 section 3.2 names these materials outright; the seed row still sets the LEVEL.
# Every other monster gets the material nearest its seed row in shape.
OVERRIDES = {
    "skeleton": "BONE", "revenant_skull": "BONE",
    "slime": "GEL",
    "crystal": "STONE", "earth_elemental": "STONE",
    "scarab": "CHITIN", "insectoid": "CHITIN", "scorpion": "CHITIN", "spider": "CHITIN", "crab": "CHITIN",
    "automaton": "METAL", "sentrybot": "METAL", "gyrobot": "METAL", "dummybot": "METAL",
    "minimimic": "METAL", "mimic": "METAL", "monster_adorcised_weapon": "METAL",
    "shadow": "ETHEREAL", "hologram": "ETHEREAL",
}


def hp(stress, ykf):
    y, f, k = ykf
    if stress < y:
        return 0.0
    h = (stress - y) * k
    return h * SHATTER if stress >= f else h


def class_mult(ci, mat):
    _, kind, p, a = CLASSES[ci]
    if kind is None:
        return 1.0
    s = p / a
    ref = hp(s, MATERIALS["FLESH"][kind])
    return min(3.0, hp(s, MATERIALS[mat][kind]) / ref) if ref > 0 else 1.0


def kind_profile(cols):
    """(impact, shear, pierce) from 7 class columns."""
    return ((cols[1] + cols[6]) / 2, (cols[0] + cols[2]) / 2, (cols[3] + cols[4]) / 2)


def shape(v):
    m = sum(v) / 3
    return tuple(x / m for x in v) if m > 0 else (1.0, 1.0, 1.0)


PHYS = (0, 1, 2, 3, 4, 6)


def shape_dist(seed, mat):
    """Distance between two 7-column rows in log-shape over the six physical columns."""
    s = [max(seed[i], 0.05) for i in PHYS]
    m = [max(mat[i], 0.05) for i in PHYS]
    ls = [math.log(x) for x in s]
    lm = [math.log(x) for x in m]
    cs, cm = sum(ls) / 6, sum(lm) / 6
    return sum(((a - cs) - (b - cm)) ** 2 for a, b in zip(ls, lm))


def main():
    text = SRC.read_text(encoding="utf-8", errors="replace")
    body = text[text.index("damagetables[NUMMONSTERS][7]"):]
    body = body[body.index("{") + 1:body.index("};")]
    rows = re.findall(r"\{([^}]*)\}\s*,?\s*//\s*(\w+)", body)
    seeds = [([float(x.strip().rstrip("f").rstrip(".") or 0) for x in r.split(",")], n) for r, n in rows]
    mat_cols = {m: [class_mult(c, m) for c in range(7)] for m in NAMES}
    out = ["// GENERATED by tools/apx/gen_materials.py from src/monster.hpp damagetables; do not edit.",
           "// Material params: {Y, F, k} for IMPACT, SHEAR, PIERCE.",
           f"static const int kApxNumMaterials = {len(NAMES)};",
           "static const char* const kApxMaterialNames[] = {" + ", ".join(f'"{n}"' for n in NAMES) + "};",
           "static const ApxMaterial kApxMaterials[] = {"]
    for n in NAMES:
        out.append("\t{{{" + "}, {".join(f"{float(y)!r}f, {float(min(f, 1e9))!r}f, {float(k)!r}f" for y, f, k in MATERIALS[n]) + f"}}}}}}, // {n}")
    out.append("};")
    out.append(f"static const int kApxNumSeedRows = {len(seeds)};")
    out.append("// per monster: material index, level (keeps the seed row's physical toughness)")
    out.append("static const ApxMonsterMaterial kApxMonsterMaterials[] = {")
    agree = 0
    for cols, name in seeds:
        cands = [m for m in NAMES if m != "UNIFORM"]
        if sum(cols[i] for i in PHYS) / 6 >= 0.75:
            cands.remove("ETHEREAL")  # ethereal is for creatures weapons barely touch (ghosts, shades)
        best = OVERRIDES.get(name) or min(cands, key=lambda m: shape_dist(cols, mat_cols[m]))
        how = "spec" if name in OVERRIDES else "seed"
        phys = [cols[i] for i in (0, 1, 2, 3, 4, 6)]
        mphys = [mat_cols[best][i] for i in (0, 1, 2, 3, 4, 6)]
        level = (sum(phys) / 6) / (sum(mphys) / 6) if sum(mphys) > 0 else 0.0
        seed_best = max(range(3), key=lambda i: kind_profile(cols)[i])
        model_best = max(range(3), key=lambda i: kind_profile(mat_cols[best])[i])
        flat = max(kind_profile(cols)) - min(kind_profile(cols)) < 0.15
        agree += 1 if (flat or seed_best == model_best) else 0
        out.append(f"\t{{{NAMES.index(best)}, {level:.4f}f}}, // {name}: {best} ({how}); seed {', '.join(f'{c:g}' for c in cols)}")
    out.append("};")
    out.append(f"// translation check: best kind agrees for {agree}/{len(seeds)} rows (rows with kind spread under 0.15 count as agree)")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out) + "\n", encoding="ascii")
    print(f"{len(seeds)} rows -> {OUT.relative_to(ROOT)}; best-kind agreement {agree}/{len(seeds)}")
    from collections import Counter
    print(Counter(l.split(": ")[1].split(" (")[0] for l in out if "; seed" in l))


if __name__ == "__main__":
    main()
