"""combat_qa.py -- the D93 C1 gate: the combat core played with REAL input through the QA driver (-apxqa=<dir>:
SDL mouse and key events pushed into the game's own queue; the OS mouse and focus are never touched), on the
normal start and on -apxfloor=1 (the named regression gate: Barony's old swing check is never reached there).

    python tools/apx/combat_qa.py --exe build/vs2022/Release/barony.exe --mode floor1 --tag c1
    python tools/apx/combat_qa.py --exe ... --mode normal
    python tools/apx/combat_qa.py --exe ... --mode floor1 --crowd 150 --perf     (cost with 150 creatures)
    python tools/apx/combat_qa.py --exe ... --mode floor1 --old                  (APX_COMBAT_OLD=1: the CONTROL)

Per family (sword axe mace spear staff dagger unarmed shield): the QA script runs /apxcombat_arena <family> (the
weapon in hand, five creatures in an arc, two behind in a line) and then swings with real clicks: a tap (quick
move), left / overhead / low (mouse motion in the first 150 ms of the wind-up), and a held click (charged move).
The game writes one JSONL row per swing and per hit (APX_COMBAT_JSONL); this tool checks every swing against the
moves table (move chosen, stamina paid = table, at least one tabled target hit) and writes the rows plus a
summary to C:\\Apocrypha\\diagnostics\\combat\\ and keeps a baseline (baseline-<mode>.json) beside them.
Takes a D70 slot (tools/apx/apx_locks.py) and closes the game with the driver's quit command.
"""
import argparse
import datetime
import json
import os
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import apx_locks  # noqa: E402

ROOT = HERE.parents[1]
DATADIR = r"C:\Program Files (x86)\Steam\steamapps\common\Barony"
OUT = Path(r"C:\Apocrypha\diagnostics\combat")
FAMILIES = ["sword", "axe", "mace", "spear", "staff", "dagger", "unarmed", "shield"]
CX, CY = 640, 360


def script_for(families, swings, settle, crowd=0, still=False):
    L = ["# generated by tools/apx/combat_qa.py", "waitlevel 1 120000", "wait 600", "shot start"]
    for fam in families:
        L += [f"console /apxcombat_arena {fam}{(' ' + str(crowd) + (' still' if still else '')) if crowd else ''}", "wait 1500" if crowd else "wait 700"]
        if "default" in swings:
            L += [f"click {CX} {CY}", "wait 1100"]
        if "left" in swings:
            L += [f"down {CX} {CY}", "look -14 0", "wait 80", f"up {CX} {CY}", "wait 1100", "look 14 0", "wait 100"]
        if "overhead" in swings:
            L += [f"down {CX} {CY}", "look 0 -14", "wait 80", f"up {CX} {CY}", "wait 1100", "look 0 14", "wait 100"]
        if "low" in swings:
            L += [f"down {CX} {CY}", "look 0 14", "wait 80", f"up {CX} {CY}", "wait 1100", "look 0 -14", "wait 100"]
        if "charged" in swings:
            L += [f"down {CX} {CY}", "wait 700", f"up {CX} {CY}", "wait 1300"]
    L += ["wait 500", "console /apxcombat_perf", "wait 300", "quit"]
    return "\n".join(L) + "\n"


def shots_script(settle, fam, delays):
    """Screenshots of a sweep through several creatures and of a charged move, taken at fixed offsets from the click."""
    a, b, c, d = delays
    L = ["# generated by tools/apx/combat_qa.py --shots", "waitlevel 1 120000", "wait 600", f"console /apxcombat_arena {fam}", "wait 900", "shot s0_rest",
         f"down {CX} {CY}", "look -14 0", f"wait {a}", "shot s1_windup_left", f"up {CX} {CY}", f"wait {b}", "shot s2_sweep", f"wait {c}", "shot s3_sweep_later",
         "wait 1300", "look 14 0", "wait 200",
         f"down {CX} {CY}", "wait 750", "shot s4_charged_windup", f"up {CX} {CY}", f"wait {d}", "shot s5_charged_active", "wait 150", "shot s6_charged_after",
         "wait 1000", "quit"]
    return "\n".join(L) + "\n"


def parse_rows(path):
    rows = []
    if path.exists():
        for line in path.read_text(errors="replace").splitlines():
            line = line.strip()
            if line.startswith("{"):
                try:
                    rows.append(json.loads(line))
                except ValueError:
                    pass
    return rows


def evaluate(rows, families, swings):
    """One verdict per expected swing: the move the table gives, stamina paid = table, at least one target hit."""
    sw = [r for r in rows if r.get("ev") == "swing"]
    hits = {}
    for r in rows:
        if r.get("ev") == "hit":
            hits.setdefault(r["swing"], []).append(r)
    verdicts = []
    want_dirs = {"default": ("thrust", 0), "left": ("left", 0), "overhead": ("overhead", 0), "low": ("low", 0), "charged": ("thrust", 1)}
    by_fam = {}
    for r in sw:
        by_fam.setdefault(r["fam"], []).append(r)
    for fam in families:
        got = by_fam.get(fam, [])
        for kind in swings:
            d, ch = want_dirs[kind]
            m = [r for r in got if r["charged"] == ch and (ch or r["dir"] == d)]
            v = {"fam": fam, "kind": kind, "swung": bool(m), "ok": False}
            if m:
                r = m[0]
                h = hits.get(r["swing"], [])
                v.update(move=r["move"], name=r["name"], dir=r["dir"], charged=r["charged"], cost_table=r["cost_table"], cost_paid=r["cost_paid"],
                         hits=len(h), killed=sum(x["killed"] for x in h), dmg=[x["dmg"] for x in h],
                         zones=[x["zone"] for x in h], mult=[x["mult"] for x in h], held_ticks=r["held_ticks"])
                v["cost_ok"] = abs(r["cost_paid"] - r["cost_table"]) < 0.011 and r["stamina_before"] >= r["cost_table"]
                v["hit_ok"] = len(h) >= 1
                v["ok"] = v["cost_ok"] and v["hit_ok"]
            verdicts.append(v)
    return verdicts


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--exe", required=True)
    ap.add_argument("--mode", choices=["floor1", "normal"], default="floor1")
    ap.add_argument("--tag", default="c1")
    ap.add_argument("--families", default=",".join(FAMILIES))
    ap.add_argument("--swings", default="default,left,overhead,low,charged")
    ap.add_argument("--crowd", type=int, default=0, help="spawn this many standing creatures around the player (perf gate: 150)")
    ap.add_argument("--still", action="store_true", help="crowd of standing training dummies (stable hits); without it the crowd fights back")
    ap.add_argument("--perf", action="store_true", help="fewer swings, only the perf rows matter")
    ap.add_argument("--old", action="store_true", help="APX_COMBAT_OLD=1: the control (Barony's old melee path)")
    ap.add_argument("--timeout", type=float, default=420)
    ap.add_argument("--seed", type=int, default=101)
    ap.add_argument("--shots", action="store_true", help="screenshot script instead of the swing matrix (sweep through creatures, charged move)")
    ap.add_argument("--shot-delays", default="20,40,40,30", help="ms: wind-up shot, click-to-sweep shot, sweep-later shot, charged-active shot")
    ap.add_argument("--settle", type=int, default=0, help="ms to let the floor load before the script starts")
    a = ap.parse_args()
    if not a.settle:
        a.settle = 8000 if a.mode == "floor1" else 20000   # the normal start generates a full level
    families = [f for f in a.families.split(",") if f]
    swings = [s for s in a.swings.split(",") if s]
    stamp = f"{datetime.datetime.now():%Y%m%d-%H%M%S}"
    run = OUT / "runs" / f"{stamp}-{a.tag}-{a.mode}{'-old' if a.old else ''}"
    qa = run / "qa"
    qa.mkdir(parents=True)
    if a.shots:
        (qa / "cmd.txt").write_text(shots_script(a.settle, families[0], [int(x) for x in a.shot_delays.split(",")]))
    else:
        (qa / "cmd.txt").write_text(script_for(families, swings, a.settle, a.crowd, a.still))
    jsonl = run / "combat.jsonl"
    env = dict(os.environ, BARONY_DATADIR=DATADIR, APX_COMBAT_JSONL=str(jsonl), APX_DIAG_DIR=str(run))
    if a.crowd:
        env["APX_COMBAT_QA"] = f"{families[0]}:{a.crowd}"
    if a.old:
        env["APX_COMBAT_OLD"] = "1"
    args = [str(Path(a.exe).resolve()), "-windowed", "-size=1280x720", "-quickstart=barbarian", f"-apxqa={qa}"]
    if a.mode == "floor1":
        args += ["-apxfloor=1", f"-apxmapseed={a.seed}"]
    slot = apx_locks.take_slot(f"combat-qa {a.tag}", 4 * 3600)
    t0 = time.monotonic()
    try:
        p = subprocess.Popen(args, cwd=run, env=env)
        try:
            p.wait(a.timeout)
            ended = "exited"
        except subprocess.TimeoutExpired:
            p.terminate()
            try:
                p.wait(15)
            except subprocess.TimeoutExpired:
                p.kill()
            ended = "timeout-terminated"
    finally:
        slot.unlink(missing_ok=True)
    rows = parse_rows(jsonl)
    OUT.mkdir(parents=True, exist_ok=True)
    legacy = {}
    if a.old:   # the control: what Barony's own path did (its log lines), since the core's rows do not exist
        log = (run / "log.txt").read_text(errors="replace") if (run / "log.txt").exists() else ""
        legacy = {"legacy_swings": log.count("[apx-stamina] swing p="), "legacy_hits": log.count("[apx-f4c] hit uid=")}
    verdicts = evaluate(rows, families, swings)
    perf = [r for r in rows if r.get("ev") == "perf"]
    ok = sum(1 for v in verdicts if v["ok"])
    swung = sum(1 for v in verdicts if v["swung"])
    summary = {
        "run": str(run), "mode": a.mode, "old_control": a.old, "ended": ended, "secs": round(time.monotonic() - t0, 1),
        "exe": a.exe, "families": families, "swings_expected": len(verdicts), "swung": swung, "ok": ok,
        "pass": ok == len(verdicts) and not a.old, "crowd": a.crowd,
        "perf": perf[-3:], "hits_total": sum(1 for r in rows if r.get("ev") == "hit"),
        "setup": [r for r in rows if r.get("ev") in ("equip", "qa_setup", "arena")][:20],
        "verdicts": verdicts, "seed": a.seed, **legacy,
    }
    (run / "summary.json").write_text(json.dumps(summary, indent=1))
    with open(OUT / f"c1-gate-{a.mode}{'-old' if a.old else ''}.jsonl", "a") as f:
        for v in verdicts:
            f.write(json.dumps(dict(v, run=run.name, mode=a.mode, old=a.old)) + "\n")
        for r in perf:
            f.write(json.dumps(dict(r, run=run.name, mode=a.mode, old=a.old, crowd=a.crowd)) + "\n")
    base = OUT / f"baseline-{a.mode}{'-old' if a.old else ''}.json"
    if summary["pass"] and not base.exists():
        base.write_text(json.dumps({"run": run.name, "ok": ok, "of": len(verdicts), "verdicts": verdicts}, indent=1))
    print(f"run {run} ended={ended} secs={summary['secs']}")
    for v in verdicts:
        print("  {fam:8s} {kind:9s} {res}  {extra}".format(
            fam=v["fam"], kind=v["kind"], res="ok  " if v["ok"] else ("FAIL" if v["swung"] else "NOSWING"),
            extra=(f"move={v.get('name')} dir={v.get('dir')} cost={v.get('cost_paid')}/{v.get('cost_table')} hits={v.get('hits')} held={v.get('held_ticks')}" if v["swung"] else "")))
    for r in perf[-2:]:
        print("  perf", json.dumps(r))
    if a.old:
        print("  control (Barony's old path):", legacy)
    print(f"GATE c1 {a.mode}{' (old control)' if a.old else ''}: {ok}/{len(verdicts)} swings ok, {swung} swung -> {'PASS' if summary['pass'] else 'FAIL'}; {run / 'summary.json'}")
    sys.exit(0 if summary["pass"] else 1)


if __name__ == "__main__":
    main()
