"""gen_props_inc.py -- embeds data/apx/props.json as src/apx/props_table.inc (card BP1): the JSON is the
source, the engine reads the embedded table so a release needs no extra file. Run after any edit:
    python -I tools/apx/gen_props_inc.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def q(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    doc = json.loads((ROOT / "data/apx/props.json").read_text(encoding="ascii"))
    out = ["// generated by tools/apx/gen_props_inc.py from data/apx/props.json; do not edit",
           "static const std::vector<PropRow> kPropTable = {"]
    for p in doc["props"]:
        m, par = p["match"], p.get("params", {})
        ftype = m["type"] if m["behavior"] == "furniture" else -2
        coll = m["type"] if m["behavior"] == "collider" else ""
        outs = []
        for o in p.get("outcomes", []):
            s = o.get("spawn") or {}
            items = ", ".join(q(i) for i in o.get("items", []))
            outs.append(f"{{ {o['pm']}, {q(s.get('kind', ''))}, {s.get('n', 0)}, {q(s.get('tier', ''))}, {{ {items} }}, {q(o.get('yield', ''))} }}")
        out.append(f"\t{{ {q(p['id'])}, {q(m['behavior'])}, {ftype}, {q(coll)}, {q(p['verb'])}, {q(p.get('label', ''))}, "
                   f"{par.get('ticks', 0)}, {par.get('heal_every', 0)}, {par.get('hunger', 0)}, {par.get('encounter_pm', 0)}, "
                   f"{par.get('encounter_max', 0)}, {par.get('regen_mult', 0)}, {par.get('reach', 28)}, {{ {', '.join(outs)} }} }},")
    out.append("};")
    (ROOT / "src/apx/props_table.inc").write_text("\n".join(out) + "\n", encoding="ascii", newline="\n")
    print(f"{len(doc['props'])} props")


if __name__ == "__main__":
    main()
