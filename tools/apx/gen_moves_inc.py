"""gen_moves_inc.py -- data/apx/combat/moves.json -> src/apx/combat/moves_table.inc (the D93 combat core's move table).
    python tools/apx/gen_moves_inc.py [--check]   (--check exits 1 when the .inc is stale; verify_all runs it)
The .inc is committed so a build never needs Python. Rows: struct MoveRow in src/apx/combat/core.hpp."""
import json, math, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "data/apx/combat/moves.json"
OUT = ROOT / "src/apx/combat/moves_table.inc"
FAM = ["none", "sword", "axe", "mace", "spear", "staff", "dagger", "unarmed", "shield"]
KIND = {"impact": 0, "shear": 1, "pierce": 2}
EFF = {"shield_aside": 0, "shield_break": 1, "slam": 2, "push": 3, "knockdown_small": 4, "crit_bleed": 5, "throw": 6, "sneak": 7, "dash": 8, "grapple": 9}
ZONE = {"auto": -1, "head": 0, "torso": 1, "arms": 2, "legs": 3}

def build():
    d = json.loads(SRC.read_text())
    ids = [m["id"] for m in d["moves"]]
    assert len(ids) == len(set(ids)), "duplicate move id"
    assert all(i < 256 for i in ids), "move ids ride in the ATAK packet byte"
    L = ["// GENERATED by tools/apx/gen_moves_inc.py from data/apx/combat/moves.json; do not edit.",
         "// id, family, name, kind, windupMs, activeMs, recoverMs, arcHalfRad, reach, extra, f1, f2, damage, staminaMult, heavyPct, effects,",
         "// armourIgnore, force, knockdownTicks, radius, dash, sneakMult, charged, momentum, area, poise, zone, sound",
         "static const MoveRow kMoveRows[] = {"]
    for m in d["moves"]:
        eff = 0
        for e in m["effects"]:
            eff |= 1 << EFF[e]
        L.append('\t{%d, %d, "%s", %d, %d, %d, %d, %.6ff, %.3ff, %d, %.3ff, %.3ff, %.3ff, %.3ff, %d, %du, %.3ff, %.3ff, %d, %.3ff, %.3ff, %.3ff, %s, %.3ff, %.3ff, %d, %d, %d},' % (
            m["id"], FAM.index(m["family"]), m["name"], KIND[m["kind"]], m["windupMs"], m["activeMs"], m["recoverMs"],
            math.radians(m["arcHalfDeg"]), m["reach"], m["extraTargets"], m["falloff1"], m["falloff2"], m["damage"], m["staminaMult"],
            m["heavyPct"], eff, m["armourIgnore"], m["force"], m["knockdownTicks"], m["radius"], m["dash"], m["sneakMult"],
            "true" if m["charged"] else "false", m["momentum"], m["area"], m["poise"], ZONE[m["zone"]], m["sound"]))
    L.append("};")
    L.append("// per family: thrust (default), left, right, overhead, low, charged move ids")
    L.append("static const int kFamilyDirs[][7] = {")
    for i, f in enumerate(FAM):
        if f == "none":
            L.append("\t{0, 0, 0, 0, 0, 0, 0},")
            continue
        v = d["families"][f]
        L.append("\t{%d, %d, %d, %d, %d, %d, %d}, // %s" % (i, v["thrust"], v["left"], v["right"], v["overhead"], v["low"], v["charged"], f))
    L.append("};")
    L.append("static const int kChargeHoldTicks = %d; static const int kDirectionWindowMs = %d; static const int kHitStopMs = %d;" % (
        d["chargeHoldTicks"], d["directionWindowMs"], d["hitStopMs"]))
    L.append("static const float kChargedStaminaMult = %.3ff; static const float kSwingWhileBlockStaminaMult = %.3ff;" % (d["chargedStaminaMult"], d["swingWhileBlockMult"]))
    return "\n".join(L) + "\n"

if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
    OUT.write_text(text, newline="\n")
    print("wrote", OUT)
