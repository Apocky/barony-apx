"""combat_c2_gate.py -- the D93 C2 gate: every defence verb by REAL input through the QA driver (-apxqa), -apxfloor=1 seed 1234567.

    python tools/apx/combat_c2_gate.py --exe build/vs2022/Release/barony.exe [--swings 70] [--old]

Verbs (keys: Block Q, Dodge Space, Kick V; Attack = left mouse):
  timed block   Q pressed, a creature hit lands N ticks (20 ms) later (/apxcombat_probe N): free up to 200 ms, not after -> boundary measured
  block         a hit after the window: not free, surplus/10 comes off stamina
  dodge         Space: 15 stamina, hits during the first 150 ms do nothing (probe at 40..140 ms free, 280 ms not), moved by an apx::move impulse
  feint         Q pressed during an attack wind-up: swing cancelled, 10 stamina
  kick          V: 4.8 stamina, shoves the creature in front
  chamber / riposte   a swing pressed within 133 ms / 267 ms of a timed block: chamber swing at once (x2), riposte swing with a short draw (x1.5)
  attack while blocking   Q held, then a click: 1.5x stamina, block stays up
  procs         an envenomed sword, many real swings: poison on the target, weapon wear, proficiency gain observed in the hit rows
Rows: C:\\Apocrypha\\diagnostics\\combat\\c2\\ ; the control (--old, APX_COMBAT_OLD=1) must not produce the core's verbs.
"""
import argparse
import datetime
import json
import os
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import apx_locks  # noqa: E402
import combat_qa as cq  # noqa: E402

OUT = Path(r"C:\Apocrypha\diagnostics\combat\c2")
CX, CY = 640, 360


def script(swings, procs_only=False):
    L = ["# generated by tools/apx/combat_c2_gate.py", "waitlevel 1 120000", "wait 800",
         "console /apxcombat_arena shield", "wait 900", "console /apxcombat_hp 9999", "wait 300"]
    if procs_only:
        L += ["console /apxcombat_arena sword", "wait 900", "console /apxcombat_hp 9999", "console /apxcombat_envenom", "wait 300"]
        for _ in range(swings):
            L += [f"click {CX} {CY}", "wait 700"]
        return "\n".join(L + ["wait 500", "quit"]) + "\n"
    for n in range(3, 15):                       # timed block window sweep, 60..280 ms
        L += [f"console /apxcombat_probe {n}", "key q 450", "wait 700"]
    L += ["console /apxcombat_probe 30", "key q 800", "wait 800"]
    L += ["console /apxcombat_arena staff", "wait 900", "console /apxcombat_hp 9999", "wait 300", "console /apxcombat_probe 30", "key q 800", "wait 800", "console /apxcombat_probe 4", "key q 450", "wait 700", "console /apxcombat_arena shield", "wait 900", "console /apxcombat_hp 9999", "wait 300"]          # a plain block, 600 ms after the press
    for n in (2, 5, 7, 10, 14):                  # dodge: invulnerable 150 ms
        L += [f"console /apxcombat_probe {n} dodge", "key space 80", "wait 900"]
    L += ["console /apxcombat_arena shield", "wait 900", "console /apxcombat_hp 9999", "wait 300", "key v 80", "wait 700", "key v 80", "wait 700"]   # kicks at the creature in front
    # feint (needs a weapon: sword arena)
    L += ["console /apxcombat_arena sword", "wait 900", "console /apxcombat_hp 9999", "wait 300"]
    L += [f"down {CX} {CY}", "wait 60", "key q 60", f"up {CX} {CY}", "wait 900"]
    # chamber and riposte need a shield up: sword and shield cannot both be held by the arena helper, so equip by console
    L += ["console /apxcombat_arena shield", "wait 900", "console /apxcombat_hp 9999", "wait 300"]
    L += ["console /apxcombat_probe 3", "key q 100", f"click {CX} {CY}", "wait 1200"]          # chamber
    L += ["console /apxcombat_probe 3", "key q 100", "wait 100", f"click {CX} {CY}", "wait 1200"]   # riposte
    L += ["kdown q", "wait 150", f"click {CX} {CY}", "wait 1200", "kup q", "wait 300"]          # attack while blocking
    L += ["console /apxcombat_arena sword", "wait 900", "console /apxcombat_hp 9999", "console /apxcombat_envenom", "wait 300"]
    for _ in range(swings):
        L += [f"click {CX} {CY}", "wait 780"]
    L += ["wait 500", "console /apxcombat_perf", "wait 300", "quit"]
    return "\n".join(L) + "\n"


def ev(rows, name):
    return [r for r in rows if r.get("ev") == name]


def evaluate(rows):
    v = {}
    probes = ev(rows, "probe")
    tb = [p for p in probes if p["since_press_ticks"] >= 0]
    free = sorted(p["since_press_ms"] for p in tb if p["free"])
    notfree = sorted(p["since_press_ms"] for p in tb if not p["free"])
    last_free = max(free) if free else None
    first_not = min([m for m in notfree if last_free is None or m > last_free], default=None)
    v["timed_block"] = dict(last_free_ms=last_free, first_not_free_ms=first_not, probes=len(tb),
                            ok=last_free is not None and first_not is not None and abs(last_free - 200) <= 20 and first_not <= 240)
    blocks = [b for b in ev(rows, "block") if not b.get("brace")]
    braces = [b for b in ev(rows, "block") if b.get("brace")]
    tbrace = [t for t in ev(rows, "timed_block")][-1:] if braces else []
    v["block"] = dict(n=len(blocks), absorbed=[b.get("absorbed") for b in blocks][:3], stamina_cost=[b["stamina_cost"] for b in blocks][:3], ok=bool(blocks) and all(b.get("absorbed", 0) > 0 and abs(b["stamina_cost"] - b["absorbed"] / 10.0) < 0.01 for b in blocks))
    v["staff_brace"] = dict(blocks=len(braces), cost=[b["stamina_cost"] for b in braces][:2], timed_with_staff=len(tbrace), ok=bool(braces))
    dp = [p for p in probes if p["since_press_ticks"] < 0]   # dodge probes (no block up)
    dod = ev(rows, "dodge")
    ends = ev(rows, "dodge_end")
    v["dodge"] = dict(n=len(dod), cost=[d["cost"] for d in dod][:2], invulnerable_ms=dod[0]["invulnerable_ms"] if dod else None,
                      probes=[(p["tick"], p["free"]) for p in dp], moved=[round(e["moved"], 1) for e in ends][:6],
                      dodged_hits=len(ev(rows, "dodged")),
                      ok=len(dod) >= 5 and all(d["cost"] == 15.0 for d in dod) and all(e["moved"] > 5 for e in ends[:2]))   # later dodges may step back into a wall
    kicks = ev(rows, "kick")
    v["kick"] = dict(n=len(kicks), cost=[k["cost"] for k in kicks][:2], hit=[k["hit"] for k in kicks][:2], dmg=[k["dmg"] for k in kicks][:2], ok=len(kicks) >= 1 and kicks[0]["hit"] == 1)
    fe = ev(rows, "feint")
    v["feint"] = dict(n=len(fe), cost=[f["cost"] for f in fe][:2], ok=len(fe) >= 1 and fe[0]["cost"] == 10.0)
    rs = ev(rows, "riposte_swing")
    v["riposte"] = dict(chamber=[r["chamber"] for r in rs], ok=any(r["chamber"] == 1 for r in rs) and any(r["chamber"] == 0 for r in rs))
    sw = ev(rows, "swing")
    ub = [s for s in sw if s.get("under_block")]
    v["attack_while_blocking"] = dict(n=len(ub), cost_paid=[s["cost_paid"] for s in ub][:2], cost_table=[s["cost_table"] for s in ub][:2],
                                      ok=bool(ub) and all(abs(s["cost_paid"] - s["cost_table"]) < 0.01 and s["cost_table"] >= 12.0 - 0.01 for s in ub))
    hits = [h for h in ev(rows, "hit") if h["fam"] == "sword"]
    pois = [h for h in hits if h.get("poisoned")]
    wst = [h["wstatus"] for h in hits if "wstatus" in h]
    prof = [h["prof"] for h in hits if "prof" in h]
    v["procs"] = dict(hits=len(hits), poisoned_hits=len(pois), weapon_status_first_last=[wst[0], wst[-1]] if wst else None,
                      weapon_wear_seen=bool(wst) and min(wst) < max(wst), proficiency_first_last=[prof[0], prof[-1]] if prof else None,
                      skill_gain_seen=bool(prof) and prof[-1] > prof[0], ok=len(pois) > 0 and bool(prof) and prof[-1] > prof[0])
    return v


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--exe", required=True)
    ap.add_argument("--swings", type=int, default=70)
    ap.add_argument("--old", action="store_true")
    ap.add_argument("--procs-only", action="store_true", help="only the proc probe (use --swings 260: weapon wear is 1 in ~50 per hit)")
    ap.add_argument("--timeout", type=float, default=400)
    a = ap.parse_args()
    run = OUT / "runs" / f"{datetime.datetime.now():%Y%m%d-%H%M%S}-c2{'-old' if a.old else ''}"
    qa = run / "qa"
    qa.mkdir(parents=True)
    (qa / "cmd.txt").write_text(script(a.swings, a.procs_only))
    jsonl = run / "combat.jsonl"
    env = dict(os.environ, BARONY_DATADIR=cq.DATADIR, APX_COMBAT_JSONL=str(jsonl), APX_DIAG_DIR=str(run))
    if a.old:
        env["APX_COMBAT_OLD"] = "1"
    args = [str(Path(a.exe).resolve()), "-windowed", "-size=1280x720", "-quickstart=barbarian", "-apxfloor=1", "-apxmapseed=1234567", f"-apxqa={qa}"]
    slot = apx_locks.take_slot("combat-c2", 4 * 3600)
    try:
        p = subprocess.Popen(args, cwd=run, env=env)
        try:
            p.wait(a.timeout)
            ended = "exited"
        except subprocess.TimeoutExpired:
            p.terminate()
            ended = "timeout-terminated"
    finally:
        slot.unlink(missing_ok=True)
    rows = cq.parse_rows(jsonl)
    v = evaluate(rows)
    if a.procs_only:
        v = {"procs": v["procs"]}
        v["procs"]["ok"] = v["procs"]["ok"] and v["procs"]["weapon_wear_seen"]
    ok = all(x["ok"] for x in v.values())
    (run / "summary.json").write_text(json.dumps(dict(run=str(run), ended=ended, old=a.old, verdicts=v, pass_=ok), indent=1))
    for k, x in v.items():
        print(f"  {k:22s} {'ok  ' if x['ok'] else 'FAIL'} {json.dumps({i: j for i, j in x.items() if i != 'ok'})}")
    print(f"C2 GATE{' (old control)' if a.old else ''}: {'PASS' if ok else 'FAIL'}  {run / 'summary.json'}")
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
