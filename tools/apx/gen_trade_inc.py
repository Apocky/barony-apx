#!/usr/bin/env python3
"""gen_trade_inc.py -- embeds the BT1 trade data (data/apx/trades.json + materials/forms/salvage_materials/form_map) as
src/apx/trade_table.inc and src/apx/trade_itemcls.inc (card BT1, D73). The JSON files are the source; the engine reads the
embedded tables so a release needs no extra file. Also LINTS the references (exit 1 on any error). Run after any edit:
    python -I tools/apx/gen_trade_inc.py          (--check: exit 1 when the .inc files are stale)
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
D = ROOT / "data" / "apx"
CATS = ["metal", "wood", "hide", "fibre", "bone", "stone", "shard", "other"]
UNIT_CAT = {"ingot": "metal", "plank": "wood", "pelt": "hide", "bolt": "fibre", "bone": "bone", "rubble": "stone", "shards": "shard", "lump": "other"}
# classes a vanilla item can have: gear by main material category, plus these for non-gear (Plain family) types
EXTRA = ["provision", "reagent", "paper", "gem", "none"]
CLASSES = CATS + EXTRA


def q(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def plain_class(name):
    if re.match(r"^FOOD_", name): return "provision"
    if re.match(r"^POTION_", name): return "reagent"
    if re.match(r"^(SCROLL|SPELLBOOK|READABLE|ENCHANTED_FEATHER)_?", name): return "paper"
    if re.match(r"^GEM_", name) or re.match(r"^(RING|AMULET)_", name): return "gem"
    return "other"


def build():
    err = []
    t = json.loads((D / "trades.json").read_text(encoding="ascii"))
    mats = json.loads((D / "materials.json").read_text(encoding="ascii"))["materials"]
    forms = json.loads((D / "forms.json").read_text(encoding="ascii"))
    sal = json.loads((D / "salvage_materials.json").read_text(encoding="ascii"))["materials"]
    fmap = json.loads((D / "form_map.json").read_text(encoding="ascii"))
    types = (ROOT / "tests" / "apx" / "itemtypes.txt").read_text().split()
    cat_of = {m["id"]: UNIT_CAT[sal[m["id"]]["unit"]] for m in mats}
    mat_ids = set(cat_of)
    slot_ids = {s["id"] for s in forms["slots"]}
    roles = {s["role"] for s in forms["slots"]}
    svc = {s["id"] for s in t["services"]}
    items = set(types)
    for tr in t["trades"]:
        for b in tr["buys"]:
            if b not in CLASSES: err.append("trade %s buys unknown class %s" % (tr["id"], b))
        for g in tr["sells"]:
            for i in g.get("ids", []):
                if g["cls"] in ("material", "reagent") and i not in mat_ids: err.append("%s sells unknown material %s" % (tr["id"], i))
                if g["cls"] == "service" and i not in svc: err.append("%s sells unknown service %s" % (tr["id"], i))
            for m in g.get("materials", []):
                if m not in mat_ids: err.append("%s component material %s" % (tr["id"], m))
            for r in g.get("roles", []):
                if r not in roles: err.append("%s component role %s" % (tr["id"], r))
            lo, hi = g["picks"]
            if not (0 <= lo <= hi <= 8): err.append("%s picks range" % tr["id"])
    for p in t["provisions"] + t["lights"]:
        if p["item"] not in items: err.append("unknown item " + p["item"])
    for r in t["rare_items"]:
        if r not in items: err.append("unknown rare item " + r)

    o = ["// generated by tools/apx/gen_trade_inc.py from data/apx/trades.json (+ materials, forms, salvage_materials); do not edit"]
    o.append("static const int kLotMarkup = %d, kWorkPct = %d, kPurseBase = %d, kPursePerDepth = %d, kOfferPct = %d, kRareMarkup = %d, kRareChancePct = %d;"
             % (t["lot_markup"], t["component_workmanship_pct"], t["purse_base"], t["purse_per_depth"], t["offer_pct"], t["rare_markup"], t["rare_chance_pct"]))
    o.append("static const std::vector<MatRow> kMats = {")
    for m in mats:
        o.append("\t{ %s, %d, %d, %s }," % (q(m["id"]), m["density"], m["value_per_kg"], q(cat_of[m["id"]])))
    o.append("};")
    o.append("static const std::vector<SlotRow> kSlots = {")
    for s in forms["slots"]:
        o.append("\t{ %s, %s, %d }," % (q(s["id"]), q(s["role"]), s["volume"]))
    o.append("};")
    o.append("static const std::vector<NamedPrice> kServices = {")
    for s in t["services"]: o.append("\t{ %s, %d }," % (q(s["id"]), s["price"]))
    o.append("};")
    o.append("static const std::vector<NamedPrice> kProvisions = {")
    for s in t["provisions"]: o.append("\t{ %s, %d }," % (q(s["item"]), s["price"]))
    o.append("};")
    o.append("static const std::vector<NamedPrice> kLights = {")
    for s in t["lights"]: o.append("\t{ %s, %d }," % (q(s["item"]), s["price"]))
    o.append("};")
    o.append("static const std::vector<std::string> kRareItems = { %s };" % ", ".join(q(r) for r in t["rare_items"]))
    o.append("static const std::vector<TradeRow> kTrades = {")
    for tr in t["trades"]:
        buys = ", ".join(q(b) for b in tr["buys"])
        groups = []
        for g in tr["sells"]:
            ids = ", ".join(q(i) for i in g.get("ids", []))
            rl = ", ".join(q(i) for i in g.get("roles", []))
            ml = ", ".join(q(i) for i in g.get("materials", []))
            groups.append("{ %s, { %s }, { %s }, { %s }, %d, %d }" % (q(g["cls"]), ids, rl, ml, g["picks"][0], g["picks"][1]))
        o.append("\t{ %s, %s, %d, %s, { %s }, { %s } }," % (q(tr["id"]), q(tr["name"]), tr["store_type"], repr(float(tr["purse_factor"])), buys, ", ".join(groups)))
    o.append("};")
    inc1 = "\n".join(o) + "\n"

    cls = ["// generated by tools/apx/gen_trade_inc.py; item class per ItemType in enum order (tests/apx/itemtypes.txt)",
           "static const char* const kClassNames[] = { %s };" % ", ".join(q(c) for c in CLASSES),
           "static const unsigned char kItemClass[] = {"]
    row = []
    for n in types:
        f = fmap[n]
        if f["family"] == "Plain": c = plain_class(n)
        else: c = cat_of[f["materials"][0]]
        row.append(str(CLASSES.index(c)))
    for i in range(0, len(row), 32):
        cls.append("\t" + ",".join(row[i:i + 32]) + ",")
    cls.append("};")
    inc2 = "\n".join(cls) + "\n"
    return err, inc1, inc2


def main():
    err, inc1, inc2 = build()
    if err:
        print("\n".join(err)); return 1
    targets = {ROOT / "src/apx/trade_table.inc": inc1, ROOT / "src/apx/trade_itemcls.inc": inc2}
    if "--check" in sys.argv:
        stale = [str(p) for p, t in targets.items() if not p.exists() or p.read_text(encoding="ascii").replace("\r\n", "\n") != t]
        print("stale: " + ", ".join(stale) if stale else "up to date"); return 1 if stale else 0
    for p, t in targets.items(): p.write_text(t, encoding="ascii", newline="\n")
    print("trade_table.inc, trade_itemcls.inc written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
