"""D75: each creature type's base strength, for the strength-ordered tier cut (spec 04 section 2.1).

Reads setDefaultMonsterStats (src/stat_shared.cpp): per type the base LVL, MAXHP and STR the engine gives a new
creature, and writes src/apx/monster_strength.inc (indexed by the Monster enum of src/monster.hpp). Constants in
the build, so the host, every client and the F2 generator rank types the same way (no Stat objects, no RNG).
A type whose defaults set no LVL (slime: its colour sets it elsewhere) gets an ESTIMATED LVL of MAXHP / 10.

Run: python tools/apx/gen_strength.py           (writes the .inc)
     python tools/apx/gen_strength.py --check   (exit 1 when the .inc is stale)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ENUM_SRC = ROOT / "src" / "monster.hpp"
STATS_SRC = ROOT / "src" / "stat_shared.cpp"
OUT = ROOT / "src" / "apx" / "monster_strength.inc"


def monsters():
    text = ENUM_SRC.read_text(encoding="utf-8", errors="replace")
    body = re.search(r"enum Monster\s*:\s*int\s*\{(.*?)\};", text, re.S).group(1)
    body = re.sub(r"//[^\n]*", "", body)
    names = [n.strip() for n in body.split(",") if n.strip()]
    assert names[0] == "NOTHING" and names[-1] == "MAX_MONSTER", names[:3]
    return names[:-1]


def defaults(names):
    text = STATS_SRC.read_text(encoding="utf-8", errors="replace")
    start = text.index("void setDefaultMonsterStats(Stat* stats, int sprite)")
    text = re.sub(r"//[^\n]*", "", text[start:])
    out = {}
    for m in re.finditer(r"case \(1000 \+ ([A-Z_]+)\):", text):
        name = m.group(1)
        if name in out:
            continue
        end = text.find("break;", m.end())
        block = text[m.end():end]
        lvl = re.search(r"stats->LVL\s*=\s*(-?\d+)\s*;", block)
        hp = re.search(r"stats->MAXHP\s*=\s*(\d+)\s*;", block) or re.search(r"stats->HP\s*=\s*(\d+)\s*;", block)
        st = re.search(r"stats->STR\s*=\s*(-?\d+)\s*;", block)
        out[name] = (int(lvl.group(1)) if lvl else None, int(hp.group(1)) if hp else None, int(st.group(1)) if st else 0)
    return out


def render():
    names = monsters()
    d = defaults(names)
    rows = []
    for i, n in enumerate(names):
        lvl, hp, st = d.get(n, (None, None, 0))
        est = 0
        if lvl is None:
            est = 1
            lvl = max(1, (hp or 10) // 10)
        rows.append(f"\t{{ {lvl}, {hp or 0}, {st}, {est} }}, // {i} {n}" + (" (LVL estimated: MAXHP / 10)" if est else "")
                    + ("" if hp else " (no defaults)"))
    head = ("// GENERATED by tools/apx/gen_strength.py from src/stat_shared.cpp setDefaultMonsterStats; do not edit.\n"
            "// Per Monster type: base LVL, MAXHP, STR, LVL estimated (1) or the engine's (0). D75 strength order.\n"
            f"static const int kApxStrengthTypes = {len(names)};\n"
            "static const ApxStrength kApxStrength[] = {\n")
    return head + "\n".join(rows) + "\n};\n"


def main():
    text = render()
    if "--check" in sys.argv:
        # line endings aside (git may check the file out with CRLF)
        ok = OUT.exists() and OUT.read_bytes().decode("ascii").replace("\r\n", "\n") == text
        print("monster_strength.inc", "current" if ok else "STALE: run python tools/apx/gen_strength.py")
        return 0 if ok else 1
    OUT.write_text(text, encoding="ascii", newline="\n")
    print(f"wrote {OUT} ({text.count('{ ') } types)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
