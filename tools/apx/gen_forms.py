#!/usr/bin/env python3
"""tools/apx/gen_forms.py -- generate the F6 vanilla-type tables from src/items.hpp.

Writes (ASCII, sorted keys):
  data/apx/form_map.json    vanilla ItemType name -> {family, materials[]} (fallback family Plain)
  tests/apx/itemtypes.txt   every ItemType name, one per line (the coverage test reads it)
The family and material rules below are name patterns over Barony's ItemType names (card BF6,
data design 19-GEAR-PARTS section 2). Every type maps: what no rule names becomes Plain/Body.
  python tools/apx/gen_forms.py [--check]   (--check: exit 1 when the files are stale)
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

FAMILY_RULES = [  # first match wins; patterns are searched in the type name
    # not gear, whatever words they contain (SCROLL_ENCHANTARMOR, SPELLBOOK_FORCE_SHIELD ...)
    ("Plain", r"^(SCROLL|SPELLBOOK|POTION|FOOD|GEM|MAGICSTAFF|AMULET|RING|READABLE|ENCHANTED_FEATHER|ARTIFACT_ORB|SPELL)_"),
    ("Armour", r"^HAT_.*HELM"),
    ("Cloth", r"^HAT_"),
    ("Bows", r"(^|_)(SHORTBOW|LONGBOW|COMPOUND_BOW|BOW|CROSSBOW|SLING)(_|$)"),
    ("Shields", r"SHIELD|BUCKLER"),
    ("Fists", r"KNUCKLES|_FIST|BRASS_KNUCKLES"),
    ("Blades", r"SWORD|DAGGER|RAPIER|SCIMITAR|KATANA|SHORTSWORD|LONGSWORD|CLAYMORE|BLADE"),
    ("Hafts", r"AXE|MACE|HAMMER|SPEAR|HALBERD|TRIDENT|FLAIL|PICKAXE|_PICK$|POLEARM|SCYTHE|STAFF_QUARTER|QUARTERSTAFF"),
    ("Armour", r"HELM|BREASTPIECE|BREASTPLATE|GLOVES|GAUNTLETS|BRACERS|BOOTS|GREAVES|LEGGINGS|MASK|ARMOR|CHAIN|PLATE|MAIL"),
    ("Cloth", r"CLOAK|HAT|HOOD|ROBE|SHIRT|TUNIC|CAPE|PUNISHER|FEZ|TURBAN|CIRCLET|BANDANA|HEADBAND"),
    ("Tools", r"^TOOL_"),
]
MATERIAL_RULES = [  # name pattern -> default materials (first is the main part's)
    (r"CRYSTAL", ["glass", "silver"]),
    (r"ARTIFACT", ["aethite", "steel"]),
    (r"STEEL", ["steel", "oak", "hide"]),
    (r"IRON", ["iron", "wood", "hide"]),
    (r"BRONZE", ["bronze", "wood", "hide"]),
    (r"SILVER", ["silver", "oak", "hide"]),
    (r"GOLD", ["gold", "oak", "hide"]),
    (r"OBSIDIAN", ["obsidian", "wood", "hide"]),
    (r"BONE", ["bone", "hide"]),
    (r"LEATHER|HIDE|_FUR", ["hide", "cloth"]),
    (r"WOODEN|WOOD|_BOW$|SHORTBOW|LONGBOW|SLING|QUARTERSTAFF", ["wood", "oak", "hide"]),
    (r"CLOAK|HAT|HOOD|ROBE|SHIRT|TUNIC|CAPE|FEZ|TURBAN|BANDANA|HEADBAND", ["cloth", "hide"]),
    (r"GLASS|LENS", ["glass", "copper"]),
    (r"STONE|ROCK", ["stone", "wood"]),
]
DEFAULT_MATERIALS = {"Blades": ["iron", "wood", "hide"], "Hafts": ["iron", "wood", "hide"], "Fists": ["iron", "hide"],
                     "Bows": ["wood", "hide"], "Armour": ["iron", "hide", "cloth"], "Cloth": ["cloth", "hide"],
                     "Shields": ["wood", "iron", "hide"], "Tools": ["iron", "wood", "hide"], "Plain": ["stone"]}


def item_types():
    text = (ROOT / "src" / "items.hpp").read_text(encoding="utf-8", errors="replace")
    body = re.search(r"typedef enum ItemType\s*\{(.*?)\}\s*ItemType;", text, re.S).group(1)
    body = re.sub(r"//[^\n]*|/\*.*?\*/", "", body, flags=re.S)
    names = [re.match(r"\s*([A-Z0-9_]+)", e).group(1) for e in body.split(",") if re.match(r"\s*[A-Z0-9_]+", e)]
    return [n for n in names if n != "ITEM_ENUM_MAX"]


def family_of(name):
    for fam, pat in FAMILY_RULES:
        if re.search(pat, name):
            return fam
    return "Plain"


def materials_of(name, fam):
    for pat, mats in MATERIAL_RULES:
        if re.search(pat, name):
            return mats
    return DEFAULT_MATERIALS[fam]


def build():
    types = item_types()
    fmap = {n: {"family": family_of(n), "materials": materials_of(n, family_of(n))} for n in types}
    inc = "// generated by tools/apx/gen_forms.py from src/items.hpp: ItemType enum names in order\n" + "".join(f'"{n}",\n' for n in types)
    return types, json.dumps(fmap, indent=1, sort_keys=True) + "\n", "\n".join(types) + "\n", inc


def main():
    types, fmap, names, inc = build()
    targets = {ROOT / "data" / "apx" / "form_map.json": fmap, ROOT / "tests" / "apx" / "itemtypes.txt": names,
               ROOT / "src" / "apx" / "parts_typenames.inc": inc}
    if "--check" in sys.argv:
        stale = [str(p) for p, t in targets.items() if not p.exists() or p.read_text(encoding="ascii").replace("\r\n", "\n") != t]
        print("stale: " + ", ".join(stale) if stale else "up to date")
        return 1 if stale else 0
    for p, t in targets.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(t, encoding="ascii", newline="\n")
    fams = {}
    for n in types:
        fams[family_of(n)] = fams.get(family_of(n), 0) + 1
    print(f"{len(types)} item types -> {fams}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
