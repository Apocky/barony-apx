"""Generate src/apx/variants_table.inc from data/apx/variants/*.json (after the lint passes).
    python -I tools/apx/gen_variants.py          (writes the .inc; refuses when the lint fails)
Loot is resolved here (extends + reweight + add), so the engine reads a flat, final table per node."""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import variants_lint as vl  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "data/apx/variants"
OUT = ROOT / "src/apx/variants_table.inc"


def main():
    errs = vl.lint(DATA)
    if errs:
        print("\n".join(errs))
        print("gen_variants: lint failed, nothing written")
        return 1
    nodes = vl.load(DATA)
    order = []
    # base first, then depth-first so a parent always precedes its children
    def walk(nid):
        order.append(nid)
        for k in sorted(i for i, l in nodes.items() if l[0].get("parent") == nid):
            walk(k)
    for b in sorted(i for i, l in nodes.items() if l[0].get("level") == "base"):
        walk(b)
    idx = {nid: i for i, nid in enumerate(order)}
    lines = ["// GENERATED by tools/apx/gen_variants.py from data/apx/variants/*.json; do not edit.",
             "// %d nodes. Loot tables are resolved (extends, reweight, add)." % len(order), "static const VLoot V_LOOT[] = {"]
    loot_first = {}
    n = 0
    for nid in order:
        t = vl.resolve_loot(nodes, nid)
        loot_first[nid] = (n, len(t))
        for k, v in sorted(t.items()):
            lines.append('\t{ "%s", %.6g },' % (k, v))
            n += 1
    lines.append("};")
    lines.append("static const VNode V_NODES[] = {")
    for nid in order:
        nd = nodes[nid][0]
        par = idx[nd["parent"]] if nd.get("parent") else -1
        st = nd.get("stats", {"hp": 1, "dmg": 1, "speed": 1, "poise": 1})
        lk = nd.get("look", {"tint": "#ffffff", "scale": 1.0, "light": "none"})
        lvl = vl.LEVELS.index(nd["level"])
        lf, lc = loot_first[nid]
        lines.append('\t{ "%s", %d, %d, %.6g, %d, %d, %.6g, %.6g, %.6g, %.6g, "%s", %d, %d, "%s", "%s", %.6g, "%s", %d, %d, "%s" },' % (
            nid, par, lvl, nd.get("rarity", 1.0), nd.get("depth_min", 1), nd.get("depth_max", 15), st["hp"], st["dmg"], st["speed"], st["poise"],
            nd.get("material", ""), nd.get("tier_shift", 0), nd.get("max_group", 99), ";".join(nd.get("traits", [])), lk["tint"], lk["scale"],
            lk["light"], lf, lc, nd.get("monster", "")))
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="ascii")
    print("wrote %s: %d nodes, %d loot rows" % (OUT.relative_to(ROOT), len(order), n))
    return 0


if __name__ == "__main__":
    sys.exit(main())
